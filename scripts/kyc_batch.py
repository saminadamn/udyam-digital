"""Run applicants K01-K12 through app.kyc (the same OCR + checks the API uses) and write docs/kyc_results.md."""
import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.kyc import checks, ocr  # noqa: E402
from app.kyc.registry import CsvRegistry  # noqa: E402
from app.security.masking import mask_gstin, mask_udyam  # noqa: E402

DOCS = ROOT / "data" / "kyc_documents"
EXPECTED = {"K01": "blocked", "K04": "reupload", "K05": "reupload", "K06": "review", "K07": "review", "K11": "reupload"}
LABEL = {"blocked": "Blocked", "reupload": "Re-upload needed", "review": "Human review", "verified": "Verified"}
CODES = ["DOCUMENT_PRESENT", "DOCUMENT_READABLE", "GSTIN_FORMAT", "GSTIN_MATCHES_CERTIFICATE", "GSTIN_EXISTS", "GSTIN_ACTIVE", "GSTIN_STATE_CODE",
         "UDYAM_EXISTS", "UDYAM_NAME_MATCH", "NAMES_MATCH", "SIGNATORY_FOR_BUSINESS", "ADDRESS_MATCH", "ADDRESS_PROOF_DATE"]
SHORT = {"DOCUMENT_PRESENT": "All 4 docs", "DOCUMENT_READABLE": "Readable", "GSTIN_FORMAT": "GSTIN format", "GSTIN_MATCHES_CERTIFICATE": "GSTIN = cert",
         "GSTIN_EXISTS": "GSTIN exists", "GSTIN_ACTIVE": "GSTIN Active", "GSTIN_STATE_CODE": "State code", "UDYAM_EXISTS": "Udyam exists",
         "UDYAM_NAME_MATCH": "Udyam name", "NAMES_MATCH": "Names match", "SIGNATORY_FOR_BUSINESS": "ID for business", "ADDRESS_MATCH": "Address city/state",
         "ADDRESS_PROOF_DATE": "Proof <= 90 days"}


def run_all():
    reg = CsvRegistry(ROOT / "data")
    out = []
    for k in sorted({p.name[:3] for p in DOCS.glob("K*.png")}):
        docs = {}
        for t in ocr.DOC_TYPES:
            p = DOCS / f"{k}_{t}.png"
            docs[t] = ocr.run(t, p.read_bytes()) if p.exists() else None
        r = checks.evaluate(docs, reg, "en", date(2026, 7, 15), 90)
        r["applicant"] = k
        r["ocr"] = {t: (None if d is None else {"confidence": d.confidence, "sharpness": d.sharpness, "skew": d.skew_deg, "readable": d.readable})
                    for t, d in docs.items()}
        out.append(r)
    return out


def cell(rows):
    if not rows:
        return "–"
    fails = [c for c in rows if c["result"] == "fail"]
    return "**FAIL**" if fails else "pass"


def write(results):
    md = ["# KYC results: applicants K01–K12", "",
          "Generated by `scripts/kyc_batch.py`, which runs the 47 images in `data/kyc_documents` through the same code the API uses "
          "(`backend/app/kyc/ocr.py` and `checks.py`). Today is taken as 2026-07-15. GSTINs and Udyam numbers are masked. "
          "Thresholds and rules are in `docs/KYC_CHECKS.md`. A dash means the check could not run because an earlier one failed "
          "(for example, no registry lookup without a readable certificate).", "",
          "## Verdicts", "", "| Applicant | Business (registry) | GSTIN | Verdict | Expected | Why |", "|---|---|---|---|---|---|"]
    ok = True
    for r in results:
        exp = EXPECTED.get(r["applicant"], "verified")
        ok &= exp == r["verdict"]
        biz = (r["gst"] or {}).get("trade_name") or (r["udyam_record"] or {}).get("enterprise_name") or ""
        why = "<br>".join(f"{c['code']}: {c['reason']}" for c in r["checks"] if c["result"] == "fail") or "all checks passed"
        md.append(f"| {r['applicant']} | {biz} | {mask_gstin(r['gstin']) or '–'} | **{LABEL[r['verdict']]}** | {LABEL[exp]} "
                  f"{'✓' if exp == r['verdict'] else '✗'} | {why} |")
    md += ["", f"All 12 verdicts match the planted problems: **{'yes' if ok else 'NO'}**.", "",
           "## Every check, every applicant", "", "| Check | " + " | ".join(r["applicant"] for r in results) + " |",
           "|---|" + "---|" * len(results)]
    for code in CODES:
        md.append(f"| {SHORT[code]} | " + " | ".join(cell([c for c in r["checks"] if c["code"] == code]) for r in results) + " |")
    md += ["", "## Reasons", ""]
    for r in results:
        md.append(f"### {r['applicant']}: {LABEL[r['verdict']]}")
        md.append("")
        md.append("| Check | Result | Severity | Reason (internal, masked) | What the customer sees |")
        md.append("|---|---|---|---|---|")
        for c in r["checks"]:
            res = "**FAIL**" if c["result"] == "fail" else "pass"
            md.append(f"| {c['code']}{' (' + c['doc_type'] + ')' if c['doc_type'] else ''} | {res} | {c['severity'] or ''} | {c['reason']} | {c['customer']} |")
        md.append("")
    md += ["## OCR quality", "", "| Applicant | Document | OCR confidence | Sharpness | Straightened |", "|---|---|---|---|---|"]
    for r in results:
        for t, d in r["ocr"].items():
            md.append(f"| {r['applicant']} | {t} | " + ("missing | | |" if d is None else f"{d['confidence']}% | {d['sharpness']} | {d['skew']:+.0f}° |"))
    (ROOT / "docs" / "kyc_results.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    safe = [{k: v for k, v in r.items() if k not in ("gst", "udyam_record")} | {"gstin": mask_gstin(r["gstin"]), "udyam": mask_udyam(r["udyam"])} for r in results]
    (ROOT / "docs" / "kyc_results.json").write_text(json.dumps(safe, indent=1, ensure_ascii=False), encoding="utf-8")
    return ok


if __name__ == "__main__":
    res = run_all()
    good = write(res)
    for r in res:
        print(r["applicant"], r["verdict"], [c["code"] for c in r["checks"] if c["result"] == "fail"])
    print("MATCH" if good else "MISMATCH")
    sys.exit(0 if good else 1)
