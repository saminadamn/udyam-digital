from sqlalchemy import Float, ForeignKey, Integer, String, Text
from sqlalchemy.orm import Mapped, mapped_column

from app.models._base import Base


class Lead(Base):
    __tablename__ = "leads"
    lead_id: Mapped[str] = mapped_column(String, primary_key=True)
    origin: Mapped[str] = mapped_column(String, default="import")
    business_id: Mapped[str | None] = mapped_column(ForeignKey("businesses.id"), nullable=True)
    created_date: Mapped[str | None] = mapped_column(String, nullable=True)
    lead_source: Mapped[str | None] = mapped_column(String, nullable=True)
    business_name: Mapped[str | None] = mapped_column(String, nullable=True)
    business_type: Mapped[str | None] = mapped_column(String, nullable=True)
    segment: Mapped[str | None] = mapped_column(String, nullable=True, index=True)
    city: Mapped[str | None] = mapped_column(String, nullable=True)
    city_tier: Mapped[int | None] = mapped_column(Integer, nullable=True)
    state: Mapped[str | None] = mapped_column(String, nullable=True)
    preferred_language: Mapped[str | None] = mapped_column(String, nullable=True)
    employee_count: Mapped[int | None] = mapped_column(Integer, nullable=True)
    num_sites: Mapped[int | None] = mapped_column(Integer, nullable=True)
    annual_turnover_band: Mapped[str | None] = mapped_column(String, nullable=True)
    has_gstin: Mapped[str | None] = mapped_column(String, nullable=True)
    gstin: Mapped[str | None] = mapped_column(String, nullable=True)
    has_udyam: Mapped[str | None] = mapped_column(String, nullable=True)
    udyam_number: Mapped[str | None] = mapped_column(String, nullable=True)
    current_internet: Mapped[str | None] = mapped_column(String, nullable=True)
    current_provider: Mapped[str | None] = mapped_column(String, nullable=True)
    monthly_telecom_spend_inr: Mapped[int | None] = mapped_column(Integer, nullable=True)
    products_of_interest: Mapped[str | None] = mapped_column(String, nullable=True)
    contact_name: Mapped[str | None] = mapped_column(String, nullable=True)
    contact_role: Mapped[str | None] = mapped_column(String, nullable=True)
    stage_reached: Mapped[str | None] = mapped_column(String, nullable=True)
    outcome: Mapped[str | None] = mapped_column(String, nullable=True)
    drop_reason: Mapped[str | None] = mapped_column(String, nullable=True)
    contacted_date: Mapped[str | None] = mapped_column(String, nullable=True)
    needs_assessed_date: Mapped[str | None] = mapped_column(String, nullable=True)
    quote_accepted_date: Mapped[str | None] = mapped_column(String, nullable=True)
    kyc_complete_date: Mapped[str | None] = mapped_column(String, nullable=True)
    activated_date: Mapped[str | None] = mapped_column(String, nullable=True)
    days_lead_to_activation: Mapped[int | None] = mapped_column(Integer, nullable=True)
    customer_follow_up_calls: Mapped[int | None] = mapped_column(Integer, nullable=True)
    bundle_products: Mapped[str | None] = mapped_column(String, nullable=True)
    monthly_bundle_value_inr: Mapped[int | None] = mapped_column(Integer, nullable=True)
    one_time_setup_inr: Mapped[int | None] = mapped_column(Integer, nullable=True)
    contract_months: Mapped[int | None] = mapped_column(Integer, nullable=True)
    churned_within_6_months: Mapped[str | None] = mapped_column(String, nullable=True)
    nps_score: Mapped[int | None] = mapped_column(Integer, nullable=True)
    acquisition_cost_inr: Mapped[int | None] = mapped_column(Integer, nullable=True)
    propensity_score: Mapped[float | None] = mapped_column(Float, nullable=True)
    propensity_bucket: Mapped[str | None] = mapped_column(String, nullable=True, index=True)
    propensity_reasons: Mapped[str | None] = mapped_column(Text, nullable=True)
    advisor_outcome: Mapped[str] = mapped_column(String, default="not_started")
    assigned_agent_id: Mapped[str | None] = mapped_column(ForeignKey("agents.id"), nullable=True)
    last_contacted_at: Mapped[str | None] = mapped_column(String, nullable=True)
    lead_status: Mapped[str] = mapped_column(String, default="open")
